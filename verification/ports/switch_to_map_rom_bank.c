/* Port of SwitchToMapRomBank in home/overworld.asm. */
__attribute__((noinline, used)) void
port_switch_to_map_rom_bank(struct switch_to_map_rom_bank_state *state)
{
	struct cpu_register_state *registers = &state->registers;
	struct button_reset_state home;
	struct memory_transfer_state back;
	port_u8 saved_b = registers->b;
	port_u8 saved_c = registers->c;
	port_u8 saved_h = registers->h;
	port_u8 saved_l = registers->l;
	port_u8 map = registers->a;

	registers->c = map;
	registers->b = 0;
	registers->a = 0x03;
	home.registers = *registers;
	home.memory[0] = state->home_temp;
	home.memory[1] = state->loaded_rom_bank;
	home.memory[2] = state->home_saved_rom_bank;
	home.memory[3] = state->mapper_bank;
	home.memory[4] = 0;
	port_bankswitch_home(&home);
	*registers = home.registers;
	state->home_temp = home.memory[0];
	state->loaded_rom_bank = home.memory[1];
	state->home_saved_rom_bank = home.memory[2];
	state->mapper_bank = home.memory[3];
	registers->h = (port_u8)(MAP_HEADER_BANKS_ADDRESS >> 8);
	registers->l = (port_u8)MAP_HEADER_BANKS_ADDRESS;
	registers->f &= PORT_FLAG_Z;
	registers->h = (port_u8)((MAP_HEADER_BANKS_ADDRESS + map) >> 8);
	registers->l = (port_u8)(MAP_HEADER_BANKS_ADDRESS + map);
	registers->a = map_header_banks[map];
	state->map_rom_bank = registers->a;
	back.registers = *registers;
	back.memory[0] = state->home_saved_rom_bank;
	back.memory[1] = state->loaded_rom_bank;
	back.memory[2] = state->mapper_bank;
	port_bankswitch_back(&back);
	*registers = back.registers;
	state->loaded_rom_bank = back.memory[1];
	state->mapper_bank = back.memory[2];
	registers->a = state->map_rom_bank;
	state->loaded_rom_bank = registers->a;
	state->mapper_bank = registers->a;
	registers->b = saved_b;
	registers->c = saved_c;
	registers->h = saved_h;
	registers->l = saved_l;
}
