__attribute__((noinline, used)) void
port_initialize_toggleable_objects_flags(struct cpu_register_state *state,
	port_u8 *memory)
{
	struct fill_memory_state fm;

	fm.registers = *state;
	fm.registers.h = (port_u8)(W_TOGGLEABLE_OBJECT_FLAGS >> 8);
	fm.registers.l = (port_u8)(W_TOGGLEABLE_OBJECT_FLAGS & 0xff);
	fm.registers.b = (port_u8)(FLAGS_SIZE >> 8);
	fm.registers.c = (port_u8)(FLAGS_SIZE & 0xff);
	fm.registers.a = 0;
	fm.saved_d = state->d;
	fm.saved_e = state->e;
	fm.written = 0;
	port_fill_memory(&fm, memory);

	port_u16 hl = 0;
	port_u8 counter = 0;

	for (;;)
	{
		port_u8 map_id = toggleable_object_states[hl];
		if (map_id == 0xffu)
			break;
		port_u8 object_state = toggleable_object_states[hl + 2];
		if (object_state == OFF_STATE)
		{
			struct flag_action_state fas;

			fas.registers = *state;
			fas.registers.b = FLAG_SET;
			fas.registers.c = (port_u8)(counter & 7u);
			fas.registers.h = (port_u8)(W_TOGGLEABLE_OBJECT_FLAGS >> 8);
			fas.registers.l = (port_u8)((W_TOGGLEABLE_OBJECT_FLAGS & 0xff) +
			    counter / 8u);
			fas.value = memory[W_TOGGLEABLE_OBJECT_FLAGS + counter / 8u];
			port_toggleable_object_flag_action(&fas);
			memory[W_TOGGLEABLE_OBJECT_FLAGS + counter / 8u] = fas.value;
			*state = fas.registers;
		}
		counter++;
		memory[W_TOGGLEABLE_OBJECT_COUNTER] = counter;
		hl += 3;
	}
	/* Exit via `cp -1 / ret z` at the sentinel: A is the loaded $ff, F is
	 * the compare's Z|N, and HL is the table base advanced past the first
	 * sentinel byte by `ld a, [hli]` (228 entries, 685 bytes). */
	state->a = 0xffu;
	state->f = PORT_FLAG_Z | PORT_FLAG_N;
	state->h = (port_u8)((TOGGLEABLE_OBJECT_STATES + 685u) >> 8);
	state->l = (port_u8)((TOGGLEABLE_OBJECT_STATES + 685u) & 0xffu);
}
