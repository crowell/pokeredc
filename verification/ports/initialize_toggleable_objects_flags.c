/* Port of InitializeToggleableObjectsFlags in
 * engine/overworld/toggleable_objects.asm:
 *
 *   ld hl, wToggleableObjectFlags
 *   ld bc, wToggleableObjectFlagsEnd - wToggleableObjectFlags
 *   xor a
 *   call FillMemory ; proven: clears the toggleable-object flags
 *   ld hl, ToggleableObjectStates
 *   xor a
 *   ld [wToggleableObjectCounter], a
 * .toggleableObjectsLoop:
 *   ld a, [hli] / cp -1 / ret z          ; end of the states table
 *   push hl / inc hl / ld a, [hl] / cp OFF / jr nz, .skip
 *   ld hl, wToggleableObjectFlags
 *   ld a, [wToggleableObjectCounter] / ld c, a / ld b, FLAG_SET
 *   call ToggleableObjectFlagAction      ; proven: set the flag
 * .skip:
 *   ld hl, wToggleableObjectCounter / inc [hl]
 *   pop hl / inc hl / inc hl / jr .toggleableObjectsLoop
 *
 * Walks the 200-entry (map, object, state) table and sets each OFF object's
 * flag through the proven ToggleableObjectFlagAction. The table is embedded
 * and byte-verified against ROM in the proof. */

